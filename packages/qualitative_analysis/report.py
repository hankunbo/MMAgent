"""Static escaped HTML. Reads saved descriptions; never calls a model."""

import html
import json


def render(value):
    if value.get("schema_version") == "qualitative-case-description/1.1.0":
        return render_integrated(value)

    def show(item):
        return "<pre>" + html.escape(json.dumps(item, ensure_ascii=False, indent=2)) + "</pre>"

    parts = [
        "<!doctype html><html lang='zh'><meta charset='utf-8'>",
        "<title>数据定性分析结果</title>"
        "<style>body{font:16px system-ui;margin:2em;max-width:1100px}"
        "pre{white-space:pre-wrap;overflow-wrap:anywhere;background:#f3f6f8;padding:1em}"
        "details{border:1px solid #ccd;padding:1em;margin:1em 0}img{max-width:450px}</style>",
        "<h1>数据定性分析结果</h1><p>仅描述数据。模型标签不等于独立确认；"
        "未知单位、眼别及原始数值不由推断覆盖。没有检查需求或疾病评分。</p>",
        "<h2>范围与完成情况</h2>",
        show(value["scope"]),
        show(value["coverage"]),
        "<h2>执行记录</h2>",
        show(value["execution"]),
    ]
    for row in value["components"]:
        parts += ["<details open><summary>" + html.escape(row["component_id"]) + "</summary>"]
        for title, field in [
            ("1 数据类型与模态", "type_modality"),
            ("2 内容与区域", "content_regions"),
            ("3 可见状况", "visibility"),
            ("4 数值语义与推断", "semantics"),
            ("5 来源眼别与访视", "source_declared"),
            ("6 分析状态与追溯", "execution"),
        ]:
            parts += ["<h3>" + title + "</h3>", show(row[field])]
        if row.get("model_annotations"):
            parts += [
                "<h3>全部模型标注（保留依据、限制与位置）</h3>",
                show(row["model_annotations"]),
                show(row.get("unconfirmed")),
            ]
        jid = row["execution"].get("job_id")
        for view in row.get("sampled_views", []):
            # IDs generated by the owner, not arbitrary model URLs or filenames.
            src = f"../views/{jid}-{view['view_id']}.png"
            parts += [
                f"<img alt='{html.escape(view['view_id'])}' src='{html.escape(src)}'>",
                show(view),
            ]
        parts.append("</details>")
    parts += [
        "<h2>背景资料</h2>",
        show(value["background"]),
        "<h2>组件关系</h2>",
        show(value["relations"]),
        "<h2>未选材料</h2>",
        show(value["scope_excluded"]),
        "</html>",
    ]
    return "\n".join(parts)


def render_integrated(value):
    from .integration import EYES, NAMES

    def esc(x):
        return html.escape(str(x))

    def show(x):
        return "<pre>" + esc(json.dumps(x, ensure_ascii=False, indent=2)) + "</pre>"

    def table(headers, rows):
        return (
            "<table><tr>"
            + "".join("<th>" + esc(x) + "</th>" for x in headers)
            + "</tr>"
            + "".join(
                "<tr>" + "".join("<td>" + esc(x) + "</td>" for x in row) + "</tr>" for row in rows
            )
            + "</table>"
        )

    summary = value["patient_summary"]
    parts = [
        "<!doctype html><html lang='zh'><meta charset='utf-8'><title>患者资料定性分析</title>",
        "<style>body{font:16px system-ui;margin:2em;max-width:1200px;color:#163447}"
        "details{border:1px solid #ccd;padding:1em;margin:1em 0}"
        "summary{font-weight:bold}"
        "table{border-collapse:collapse;width:100%;margin:1em 0}"
        "td,th{border:1px solid #ccd;padding:.5em;text-align:left}"
        "pre{white-space:pre-wrap;overflow-wrap:anywhere;background:#f3f6f8;padding:1em}"
        "img{max-width:95%;width:580px}"
        ".warn{color:#934200}"
        "</style>",
        "<h1>患者级资料汇总与逐项定性分析</h1>",
        "<p>来源事实、模型观察与方法推断分层保存；本页不诊断、不计疾病分、不生成检查需求。</p>",
        "<h2>患者资料汇总</h2>",
        table(
            ["组件数", "背景字段数", "已完成视觉分析的组件数", "未取得组件"],
            [
                [
                    summary["component_count"],
                    summary["background_count"],
                    len(summary["visual_completed_components"]),
                    ", ".join(summary["unavailable_components"]),
                ]
            ],
        ),
        table(
            ["眼别", "访视", "相对基线年", "资料编号"],
            [
                [
                    EYES[v["laterality"]],
                    v["source_visit"],
                    v["interval_years"],
                    ", ".join(v["component_ids"]),
                ]
                for v in summary["eye_visit_groups"]
            ],
        ),
        "<p>基线与访视编号分别保留；相对时间相同不自动合并事件。未将左右眼的同编号访视视为同一天。</p>",
        "<h3>背景资料</h3>",
        table(
            ["编号", "字段", "原值", "眼别", "访视", "状态/语义"],
            [
                [
                    b["id"],
                    b["concept"],
                    b["value"],
                    EYES[b["laterality"]],
                    b["visit"],
                    b["status"] + " / " + b["meaning_status"],
                ]
                for b in summary["background"]
            ],
        ),
        "<details><summary>精确相同内容关系</summary>"
        + show(summary["identical_payload_groups"])
        + "</details>",
        "<h3>共同边界（统一说明）</h3><ul>"
        + "".join("<li>" + esc(x) + "</li>" for x in summary["shared_limits"])
        + "</ul>",
        "<details><summary>运行、范围与版本记录</summary>"
        + show(value["coverage"])
        + show(value["execution"])
        + show(value["scope"])
        + "</details>",
    ]
    states = {
        "completed": "视觉分析完成",
        "not_requested": "结构数据已读取",
        "material_unavailable": "资料未提供",
        "pending": "视觉待执行",
    }
    if value.get("derivation", {}).get("operation") == "supplement_confirmed_same_contract":
        parts += [
            "<p><strong>本例视觉资料补全：</strong>"
            + (
                "全部有图像组件已取得同版本已确认分析。"
                if value["coverage"]["case_visual_completed"]
                else "仍有未完成组件。"
            )
            + "原轮次失败与 UNKNOWN 仍保留在历史账本，不表示旧请求已确认。</p>",
            show(
                dict(
                    supplemented_components=value["coverage"]["supplemented_components"],
                    cumulative_api_requests=value["execution"]["cumulative_api_requests"],
                )
            ),
        ]
    if (
        value.get("derivation", {}).get("operation")
        == "combine_confirmed_data_with_explicit_historical_fallback"
    ):
        parts += [
            '<p class="warn"><strong>版本说明：</strong>部分组件复用旧版已确认观察，'
            "不代表本轮新视觉评阅已完成。原 UNKNOWN 和请求账本完整保留。</p>",
            show(value["coverage"].get("historical_fallback_components", [])),
        ]
    for row in value["components"]:
        s, integrated = row["source_declared"], row["integrated"]
        title = "｜".join(
            [
                row["component_id"],
                NAMES.get(s["concept"], s["concept"]),
                EYES[s["laterality"]],
                "访视 " + s["visit"],
                "已提供" if s["status"] == "obtained" else s["status"],
                states.get(row["execution"]["visual"], row["execution"]["visual"]),
            ]
        )
        if row["execution"].get("historical_fallback"):
            title += "｜复用旧版视觉记录（新版未完成）"
        if row["execution"].get("supplemental_confirmation"):
            title += "｜新版独立补评已确认"
        parts += [
            '<details open id="'
            + esc(row["component_id"])
            + '"><summary>'
            + esc(title)
            + "</summary>",
            "<h3>1 数据类型、模态与眼别</h3>",
            show(
                dict(
                    kind=s["kind"],
                    modality=integrated["modality"],
                    laterality=integrated["laterality"],
                )
            ),
            "<h3>2 内容、区域与解剖结构</h3>",
        ]
        for a in integrated["anatomy"]:
            parts += [
                "<p><strong>"
                + esc(a["name"])
                + "</strong>（"
                + esc(a["identification"])
                + "） · "
                + esc(a["view_id"])
                + " · "
                + esc(a["location"])
                + "<br>依据："
                + esc(a["evidence"])
                + "<br>局部限制："
                + esc(a["limitation"])
                + "</p>"
            ]
        # Full original observational content, never abbreviated or replaced by labels.
        for a in row["content_regions"]:
            parts += [
                "<p><strong>"
                + esc(a["label"])
                + "</strong>："
                + esc(a["value"])
                + "<br>位置："
                + esc(a["location"])
                + "；依据："
                + esc(a["evidence"])
                + "</p>"
            ]
        parts += ["<h3>3 可见状况</h3>"]
        for a in row["visibility"]:
            parts += [
                "<p>"
                + esc(a["value"])
                + "<br>位置："
                + esc(a["location"])
                + "；依据："
                + esc(a["evidence"])
                + "</p>"
            ]
        parts += ["<h3>4 字段与单位依据</h3>", show(integrated["units"])]
        if integrated["field_context"]:
            parts += [
                "<details><summary>已绑定字段含义及原方法依据</summary>"
                + show(integrated["field_context"])
                + "</details>"
            ]
        if row["semantics"].get("saved_values"):
            parts += [
                "<details><summary>原始向量（未改写）</summary>"
                + show(row["semantics"]["saved_values"])
                + "</details>"
            ]
        parts += [
            "<h3>5 组织关系</h3>",
            show(
                dict(
                    laterality=s["laterality"],
                    visit=s["visit"],
                    interval_years=s["interval_years"],
                    source_refs=s["source_refs"],
                )
            ),
            "<h3>6 不确定项、状态与追溯</h3>",
            show(integrated["uncertainties"]),
            show(row["execution"]),
            "<p>局部限制索引："
            + ", ".join(
                '<a href="#' + esc(x) + '">' + esc(x) + "</a>"
                for x in integrated["limitation_refs"]
            )
            + "</p>",
            "<details><summary>术语对齐与真实冲突</summary>"
            + show(integrated["terminology_comparisons"])
            + show(row.get("conflicts", []))
            + "</details>",
            "<details><summary>原始来源声明与模型记录（不覆盖，原“不确认”不等于来源未知）</summary>"
            + show(s)
            + show(row.get("model_annotations", []))
            + show(row.get("unconfirmed", []))
            + "</details>",
        ]
        jid = row["execution"].get("job_id")
        for view in row.get("sampled_views", []):
            parts += [
                '<figure><img src="../views/'
                + esc(jid)
                + "-"
                + esc(view["view_id"])
                + '.png" alt="'
                + esc(row["component_id"] + " " + view["view_id"])
                + '"><figcaption>'
                + esc(view["view_id"])
                + "：实际发送的视图</figcaption></figure>"
            ]
        parts += ["</details>"]
    parts += ["<h2>局部限制索引（相同原文合并列示）</h2>"]
    for item in value["limitation_registry"]:
        parts += [
            '<p id="'
            + esc(item["id"])
            + '"><strong>'
            + esc(item["id"])
            + "</strong> "
            + esc(item["text"])
            + "<br>适用组件："
            + esc(", ".join(item["component_ids"]))
            + "</p>"
        ]
    return "\n".join(parts + ["</html>"])
